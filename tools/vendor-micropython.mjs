/**
 * Vendors MicroPython into `src/vendor/micropython.js`.
 *
 * The npm package ships an Emscripten glue module plus a separate .wasm that
 * the glue fetches relative to its own URL. Benseditor cannot fetch anything:
 * the single-file editor, an exported game and the Electron app all run from
 * `file://`, and the Node test suites have no server. So this script embeds
 * the wasm in the glue as base64 and seeds Emscripten's `Module.wasmBinary`,
 * which it honours everywhere -- browser, file://, Node -- with no request.
 *
 * Two edits are made to the glue, each asserted to match exactly once so an
 * upstream reshuffle fails loudly here rather than quietly at runtime:
 *
 *   1. `loadMicroPython` builds its Module options object; the wasm bytes are
 *      added to it.
 *   2. The fallback `new URL("micropython.wasm", import.meta.url)` is removed:
 *      never reached once wasmBinary is set, but Vite would otherwise try to
 *      resolve the file as an asset at build time.
 *
 *   node tools/vendor-micropython.mjs           write src/vendor/micropython.js
 *   node tools/vendor-micropython.mjs --check   fail if it is out of date
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = join(root, 'node_modules', '@micropython', 'micropython-webassembly-pyscript');
const target = join(root, 'src', 'vendor', 'micropython.js');
const check = process.argv.includes('--check');

const pkg = JSON.parse(await readFile(join(pkgDir, 'package.json'), 'utf8'));
const glue = await readFile(join(pkgDir, 'micropython.mjs'), 'utf8');
const wasm = await readFile(join(pkgDir, 'micropython.wasm'));

/** Replace exactly one occurrence, or explain what changed upstream. */
function patch(source, from, to, what) {
  const count = source.split(from).length - 1;
  if (count !== 1) {
    throw new Error(
      `vendor-micropython: expected exactly one match for ${what}, found ${count}. ` +
        `The glue in ${pkg.name}@${pkg.version} has changed; update the patch.`,
    );
  }
  return source.replace(from, to);
}

let out = glue;
out = patch(
  out,
  'let Module={locateFile:(path,scriptDirectory)=>url||scriptDirectory+path};',
  'let Module={wasmBinary:__benseditorWasm(),locateFile:(path,scriptDirectory)=>url||scriptDirectory+path};',
  'the Module options in loadMicroPython',
);
out = patch(
  out,
  'new URL("micropython.wasm",import.meta.url).href',
  '""',
  'the wasm URL fallback',
);

const header = `/* eslint-disable */
// @ts-nocheck
/*
 * ${pkg.name}@${pkg.version} (MIT), with the wasm embedded.
 * GENERATED by tools/vendor-micropython.mjs -- do not edit; re-run the script.
 */
const __BENSEDITOR_WASM_BASE64 = ${JSON.stringify(wasm.toString('base64'))};
function __benseditorWasm() {
  const binary = atob(__BENSEDITOR_WASM_BASE64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}
`;

const result = header + out;

if (check) {
  let current = '';
  try {
    current = await readFile(target, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== result) {
    console.error('src/vendor/micropython.js is out of date: run `node tools/vendor-micropython.mjs`.');
    process.exit(1);
  }
  console.log('src/vendor/micropython.js is up to date.');
} else {
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, result, 'utf8');
  console.log(`wrote ${target} (${(result.length / 1024).toFixed(0)} KB, wasm ${(wasm.length / 1024).toFixed(0)} KB)`);
}
